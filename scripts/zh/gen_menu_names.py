#!/usr/bin/env python3
"""Generate core/src/gui/widgets/menu_names.h from scripts/zh/menu_names.json.

Menu titles are module instance names (config keys) or built-in entry names, so
they cannot be translated in place.  This table maps the internal name to the
drawn title; unknown names (e.g. user-created instances) are shown unchanged.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(REPO, "core", "src", "gui", "widgets", "menu_names.h")


def cxx_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    data = json.load(open(os.path.join(HERE, "menu_names.json"), encoding="utf-8"))
    entries = {}
    for group in ("core", "instances", "providers"):
        entries.update(data.get(group, {}))
    rows = ["        { %s, %s }," % (cxx_str(k), cxx_str(entries[k]))
            for k in sorted(entries, key=str.lower)]
    text = """// Generated by scripts/zh/gen_menu_names.py from scripts/zh/menu_names.json.
// Do not edit by hand.
#pragma once
#include <string>
#include <utility>

// zh-CN display name for a menu entry / module instance / sink provider.
// Only the drawn title changes: the internal name stays the config key, the
// menu-order key and the module instance name, so existing configs keep
// working and user-created instances fall through untranslated.
inline std::string menuDisplayName(const std::string& name) {
    static const std::pair<const char*, const char*> names[] = {
%s
    };
    for (const auto& entry : names) {
        if (name == entry.first) { return entry.second; }
    }
    return name;
}
""" % "\n".join(rows)
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print(f"wrote {OUT} ({len(entries)} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
